def _r(rng, lo, hi, nd=2):
    return round(rng.uniform(lo, hi), nd)

def build(seed, context=None, wet=0.0):
    """Возвращает (контекст, одежда, контейнеры, предметы, заметки).
    Всё детерминировано зерном: тот же seed — тот же человек в том же моменте."""
    rng = random.Random(f"{seed}|edc")
    notes = []

    if context is None or context == "auto":
        names = list(CONTEXTS.keys())
        weights = [CONTEXTS[n]["вес"] for n in names]
        context = rng.choices(names, weights=weights, k=1)[0]
    if context not in CONTEXTS:
        raise KeyError(f"нет такого момента переноса: {context}")
    ctx = CONTEXTS[context]

    # одежда момента, с разбросом массы и теплоизоляции
    worn = []
    for i, name in enumerate(ctx["одежда"], 1):
        if name not in WEAR:
            notes.append(f"нет в таблице одежды: {name}"); continue
        klo, khi, clo_lo, clo_hi = WEAR[name]
        worn.append({"id": f"wrn_{i:02d}", "name": name, "kg": _r(rng, klo, khi),
                     "clo": _r(rng, clo_lo, clo_hi), "layer": "—", "wet": wet})

    # какие вещи при нём: базовая вероятность × поправка момента
    picked = []
    for name, (klo, khi, llo, lhi, p, tags) in EDC.items():
        p_eff = ctx["мод"].get(name, 1.0) * p if name in ctx["мод"] else p * 0.35
        if name in ctx["мод"]:
            p_eff = min(1.0, ctx["мод"][name] if ctx["мод"][name] > p else p * ctx["мод"][name] * 2)
        if rng.random() < p_eff:
            picked.append(name)

    # контейнеры: карманы момента + рюкзак, если он выпал вещью
    cnames = list(ctx["контейнеры"])
    if "рюкзак городской" in picked and "рюкзак городской" not in cnames:
        cnames.append("рюкзак городской")
    if "рюкзак городской" in cnames and "рюкзак городской" in picked:
        picked.remove("рюкзак городской")
    containers = [{"id": "cnt_00", "name": "руки", "mount": "тело", "access_s": 0,
                   "cap_l": None, "cap_kg": None, "rigid": True, "kg": 0.0}]
    cid_of = {"руки": "cnt_00"}
    for i, cn in enumerate(cnames, 1):
        if cn not in CONTAINERS_MODERN:
            notes.append(f"нет в таблице контейнеров: {cn}"); continue
        acc, cl, ck, rigid, kg = CONTAINERS_MODERN[cn]
        cid = f"cnt_{i:02d}"; cid_of[cn] = cid
        containers.append({"id": cid, "name": cn, "mount": "тело", "access_s": acc,
                           "cap_l": cl, "cap_kg": ck, "rigid": rigid, "kg": kg})

    if not cid_of.get(cnames[0] if cnames else None) and len(containers) == 1:
        notes.append("карманов нет вовсе — всё, что не в руках, не унести")

    # раскладка с реальными массой и объёмом; что не влезло — не взято
    items, depth = [], {}
    loads = {c["id"]: [0.0, 0.0] for c in containers if c["cap_l"] is not None}
    order = [c for c in containers if c["cap_l"] is not None]
    rng.shuffle(picked)
    n = 0
    for name in picked:
        klo, khi, llo, lhi, p, tags = EDC[name]
        kg, l = _r(rng, klo, khi), _r(rng, llo, lhi)
        shuf = order[:]; rng.shuffle(shuf)
        placed = None
        for c in shuf:
            mult = 1.0 if c["rigid"] else 1.3
            nk, nl = loads[c["id"]][0] + kg, loads[c["id"]][1] + l
            if nl <= c["cap_l"] * mult and nk <= c["cap_kg"]:
                loads[c["id"]] = [nk, nl]; placed = c["id"]; break
        if not placed:
            notes.append(f"не поместилось, осталось дома: {name} ({kg} кг, {l} л)")
            continue
        n += 1
        d = depth.get(placed, 0); depth[placed] = d + 1
        it = {"id": f"itm_{n:02d}", "name": name, "kg": kg, "l": l, "qty": 1,
              "in": placed, "depth": d, "condition": _r(rng, 0.45, 1.0), "tags": tags}
        # состояние — тоже случайное и осмысленное
        if "энергия" in tags or name in ("смартфон", "ноутбук", "фонарик", "фонарик-брелок", "наушники"):
            it["charge_pct"] = rng.randint(3, 100)
        if "вода" in tags:
            it["fill"] = _r(rng, 0.0, 1.0)
        if name == "сигареты":
            it["qty_left"] = rng.randint(0, 20)
        if name == "зажигалка":
            it["fuel_pct"] = rng.randint(0, 100)
        items.append(it)

    return context, worn, containers, items, notes


