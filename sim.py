def fmt_time(S):
    c, t = S["calendar"], S["time"]["t_h"]
    d = int(t // c["day_hours"]); hod = t % c["day_hours"]
    return f"{c['start_date']}+{d}д {int(hod):02d}:{int((hod%1)*60):02d}"

