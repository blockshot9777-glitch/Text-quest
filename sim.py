    e, w = validate_ruleset(R)
    good = not e
    ok += good; fail += (not good)
    print("  %s встроенный набор чист: %d ошибок" % ("ok " if good else "MISS", len(e)))

    print("=" * 58)
    print("ИТОГО пройдено %d, провалено %d" % (ok, fail))
    sys.exit(1 if fail else 0)

