def _r(rng, lo, hi, nd=2):
    return round(rng.uniform(lo, hi), nd)

def build_edc(seed, context=None, wet=0.0):
    """Возвращает (контекст, одежда, контейнеры, предметы, заметки).
    Всё детерминировано зерном: тот же seed — тот же человек в том же моменте."""
    rng = random.Random(f"{seed}|edc")
    notes = []

    if context is None or context == "auto":
        names = list(CONTEXTS.keys())
        weights = [CONTEXTS[n]["вес"] for n in names]
        context = rng.choices(names, weights=weights, k=1)[0]
    if context not in CONTEXTS:
        raise KeyError(f"нет такого момента переноса: {context}")
    ctx = CONTEXTS[context]

    # одежда момента, с разбросом массы и теплоизоляции
    worn = []
    for i, name in enumerate(ctx["одежда"], 1):
        if name not in WEAR:
            notes.append(f"нет в таблице одежды: {name}"); continue
        klo, khi, clo_lo, clo_hi = WEAR[name]
        worn.append({"id": f"wrn_{i:02d}", "name": name, "kg": _r(rng, klo, khi),
                     "clo": _r(rng, clo_lo, clo_hi), "layer": "—", "wet": wet})

    # какие вещи при нём: базовая вероятность × поправка момента
    picked = []
    for name, (klo, khi, llo, lhi, p, tags) in EDC.items():
        p_eff = ctx["мод"].get(name, 1.0) * p if name in ctx["мод"] else p * 0.35
        if name in ctx["мод"]:
            p_eff = min(1.0, ctx["мод"][name] if ctx["мод"][name] > p else p * ctx["мод"][name] * 2)
        if rng.random() < p_eff:
            picked.append(name)

    # контейнеры: карманы момента + рюкзак, если он выпал вещью
    cnames = list(ctx["контейнеры"])
    if "рюкзак городской" in picked and "рюкзак городской" not in cnames:
        cnames.append("рюкзак городской")
    if "рюкзак городской" in cnames and "рюкзак городской" in picked:
        picked.remove("рюкзак городской")
